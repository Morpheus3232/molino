/** Llegadas de un país por ISO, o undefined si no hay dato. */
export function arrivalsOf(iso?: string | null): number | undefined {
  return iso ? ARRIVALS[iso]?.[0] : undefined;
}

/** Para ordenar países: el más visitado primero; sin dato, después. 0 si no son comparables. */
export function byArrivalsDesc(aIso?: string | null, bIso?: string | null): number {
  return (arrivalsOf(bIso) ?? -1) - (arrivalsOf(aIso) ?? -1);
}
